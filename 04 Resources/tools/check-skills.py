#!/usr/bin/env python3
"""Checker for the skill package. Two blocks, one command.

BLOCK A - card <-> executable contract (vault rule)
    The card in AIOS/skills/ is NEVER a copy of the executable.

    kind: installed -> an executable exists in .claude/; the card is a POINTER and
                       the executable is the canonical source (`canonical` field)
    kind: library   -> no executable exists; the card itself IS the canonical
                       source (`canonical: self`), so there is nothing to diverge

    Catches: a card going back to being a copy of SKILL.md · an installed
    executable with no card · a dead pointer · a library card promoted without
    converting · a SKILL.md with no name/description (Claude Code does not
    register it) · a card missing from the catalog.

BLOCK B - INTERNAL integrity of the skill
    It comes from a real defect: a content skill received a new call-to-action
    rule in its SKILL.md while its `references/` methodology file kept saying the
    opposite. That reference file is the one the skill tells the agent to read
    BEFORE writing, so the skill would deliver the wrong copy with a "correct"
    SKILL.md the whole time. Nothing in the vault looked inside the skill folder.

    Catches: a cited reference that does not exist on disk · a reference file
    that nobody cites (dead weight, or forgotten in an old state) · a cited
    sibling skill that is not installed · a third-party path that survived the
    adaptation · a cited MCP server that is not configured · an outdated model
    name.

    Does NOT catch semantic contradiction: a regex cannot decide whether two
    sentences contradict each other, and selling that as a check would be prose
    pretending to be a mechanism. For that there is the --rules mode, which puts
    the normative lines of SKILL.md and of the references side by side for a
    quick human read.

Usage:
    python "04 Resources/tools/check-skills.py"              # checks A + B
    python "04 Resources/tools/check-skills.py" --rules      # report of rules
                                                             # for review
    python "04 Resources/tools/check-skills.py" --catalog    # regenerates the
                                                             # catalog in the index

Output: findings with the file. Exit 0 = passed, 1 = there are failures.
"""
import json
import os
import re
import sys
from pathlib import Path

# Windows: a cp1252 stdout blows up on accented characters, so force UTF-8.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.stderr.reconfigure(encoding="utf-8", errors="replace")

VAULT = Path(__file__).resolve().parents[2]
CARDS = VAULT / "AIOS" / "skills"
SKILLS = VAULT / ".claude" / "skills"
CMDS = VAULT / ".claude" / "commands"
INDEX = VAULT / "AIOS" / "index.md"

POINTER_MARK = "is not the executable"
LIBRARY_MARK = "this card is the canonical source"
MAX_POINTER_LINES = 45            # a pointer past this is turning into a copy
MIN_EQUAL_LINES = 4               # long lines identical to the executable = copy
# Skills that write to the vault and therefore must declare `## Contract`.
# An explicit list on purpose: a "does it write" heuristic gives false positives
# on a skill that only CITES a path to read. Whoever is in here is in by decision.
# The migration is closed: all of them declare a contract, so all of them fail
# without one. A new writer goes in here in the same commit in which it starts
# writing.
WRITERS = ["eiirp", "ingest", "consolidate", "vault-lint", "organize",
           "curate-transcripts", "integration-review"]
CONTRACT_REQUIRED = set(WRITERS)
CONTRACT_SUBSECTIONS = ("Reads", "Writes", "Never writes")
ROUTING = VAULT / "AIOS" / "knowledge-routing.md"
RE_PLACEHOLDER = re.compile(r"YYYY|MM|DD|NNN|<[^>]+>|\{[^}]+\}")
# Looks like a top-level vault folder ("03 Projects", "AIOS", "knowledge", ".claude").
# Tells a vault path apart from a generic relative reference such as `logs/`.
RE_VAULT_TOP = re.compile(r"^(\d{2} \S|AIOS$|knowledge$|\.claude$)")

START = "<!-- SKILLS-CATALOG:START (generated by 04 Resources/tools/check-skills.py --catalog) -->"
END = "<!-- SKILLS-CATALOG:END -->"

# ---------------------------------------------------------------- block B ----
# Connectors managed by claude.ai: they do not show up in mcpServers of
# .claude.json, so they are declared here. Config servers the checker reads on
# its own (global + this project's scope), so the list does not age with the file.
MCP_CONNECTORS = {
    "claude-in-chrome", "ide", "claude_ai_Gmail", "claude_ai_Google_Calendar",
    "claude_ai_Google_Drive", "claude_ai_Supabase",
}

# Traces of someone else's environment. A third-party pack is usually born on the
# author's Mac, and a path that survives the adaptation becomes an instruction for
# the agent to read a file that does not exist.
# Open list: when you adopt a new pack, add its folders and handles here.
FOREIGN_PATHS = [
    (r"/Users/[a-z]", "absolute macOS path from someone else"),
    (r"~/Documents/00 - Projetos", "projects folder of the pack's author"),
    (r"My Second Brain", "third-party vault"),
    (r"iCloud~md~obsidian", "Obsidian vault on iCloud (macOS)"),
    (r"/Applications/", "macOS app"),
    (r"/System/Library/", "macOS system font"),
    (r"\.agents/product-marketing-context", "the pack's agency context"),
    (r"docs/agency/", "the pack's agency folder"),
    (r"00 - Research/", "research folder of a third-party vault"),
]

# Models that were retired. `gpt-image-2` is real and must not match `gpt-4`.
OUTDATED_MODELS = r"\b(claude-[123][.-]|claude-instant|gpt-4(?![a-z0-9-])|gpt-3\.5|text-davinci|(sonnet|opus|haiku)-3(?:\.5)?\b)"

# Extensions that count as a citable internal file
INTERNAL = (".md", ".py", ".mjs", ".js", ".json", ".sh", ".ts", ".html", ".css")

# A token that looks like a skill name: lowercase, hyphenated.
RE_SKILLISH = re.compile(r"`([a-z][a-z0-9]*(?:-[a-z0-9]+)+)`")
RE_MCP = re.compile(r"mcp__([A-Za-z0-9_-]+?)__")
INTERNAL_DIRS = "references|scripts|assets|evals|agents|reference|eval-viewer"
# Optional prefix pointing to another skill. Both forms are a legitimate citation
# between skills, not a broken path:
#   other-skill/references/x.md
#   ~/.claude/skills/some-other-skill/references/x.md
_PREFIX = r"(?:~?/?\.claude/skills/[a-z0-9-]+/|[a-z][a-z0-9-]*/)?"
_TARGET = r"(%s(?:%s)/[A-Za-z0-9._/-]+)" % (_PREFIX, INTERNAL_DIRS)
# Markdown link = intent to navigate, the file MUST exist -> failure.
RE_MD_LINK = re.compile(r"\]\(%s\)" % _TARGET)
# A bare or backticked path (reference table, prose) = a real citation, but it
# can be illustrative (a skill-creator describes the STRUCTURE of a skill that
# does not exist yet) -> warning, not failure.
RE_BARE_PATH = re.compile(r"(?<!\]\()\b%s" % _TARGET)
# The check fires on a CLAIM, not on a mention. A line that forbids the use, or
# that denies the existence, is not the skill promising anything: it is the skill
# warning you.
RE_NEGATION = re.compile(
    r"(?i)\b(never|forbidden|prohibited|blocks?\b|blocked|banned|no longer|"
    r"(?:is|are|was|were|do|does|did|has|have) not\b|"
    r"isn't|aren't|wasn't|don't|doesn't|didn't|"
    r"there is no|not (?:by|through)|"
    r"old name|old\b|former|was never|human discipline)")
# A line that declares the path as someone else's is already the correction.
RE_FOREIGN = re.compile(
    r"(?i)(source vault|original vault|someone else's|the author|author's|"
    r"third[- ]party|did not come|didn't come|did not travel|not here|"
    r"no point (?:in )?looking|"
    r"(?:is|are|was|were) not installed|never installed|do not exist|"
    r"does not exist|doesn't exist|were dropped|was dropped|removed|"
    r"skill here|no skill)")
RE_HOOK = re.compile(r"`?([~\w./\\-]*hooks/[A-Za-z0-9._-]+\.(?:py|sh|js|mjs))`?")
HOOK_DIRS = [Path(os.path.expanduser("~/.claude/hooks")), VAULT / ".claude" / "hooks"]
# A line that carries a hard rule, for the --rules report
RE_NORMATIVE = re.compile(
    r"(?i)\b(never|always|mandatory|required|forbidden|prohibited|fails?\b|"
    r"only (?:in|when|if|counts|exists)|"
    r"must not|cannot|can't|do not use|don't use|default\b|gate\b)"
)


def frontmatter(text):
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    fm = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if m:
            fm[m.group(1)] = m.group(2).strip()
    return fm, text[end + 4:].lstrip("\n")


def read(p):
    return p.read_text(encoding="utf-8", errors="replace")


def dense_lines(text):
    """Lines long enough that a literal match means a copy."""
    out = set()
    for line in text.splitlines():
        s = line.strip()
        if len(s) >= 45 and not s.startswith(("#", ">", "|", "---")):
            out.add(s)
    return out


def executable_of(name):
    p = SKILLS / name / "SKILL.md"
    if p.exists():
        return ".claude/skills/%s/SKILL.md" % name
    p = CMDS / (name + ".md")
    if p.exists():
        return ".claude/commands/%s.md" % name
    return None


def load_cards():
    cards = {}
    for file in sorted(CARDS.glob("*.md")):
        if file.name.startswith("_"):
            continue
        fm, body = frontmatter(read(file))
        cards[file.stem] = {"file": file, "fm": fm, "body": body}
    return cards


def summary_of(body):
    """First useful sentence of the body, for the generated catalog."""
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith(("#", ">", "-", "|", "**Invoke", "---")):
            continue
        s = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", s)
        s = re.sub(r"\[\[([^\]]+)\]\]", r"\1", s)
        s = s.replace("**", "")
        if len(s) > 120:
            return s[:118].rsplit(" ", 1)[0].rstrip(".,;:") + "..."
        return s
    return ""


def check(cards):
    failures, warnings = [], []
    index_text = read(INDEX) if INDEX.exists() else ""

    for name, c in sorted(cards.items()):
        rel = c["file"].relative_to(VAULT).as_posix()
        fm, body = c["fm"], c["body"]
        kind, can = fm.get("kind"), fm.get("canonical")
        real = executable_of(name)

        if kind not in ("installed", "library"):
            failures.append((rel, "NO KIND", "frontmatter needs kind: installed | library"))
            continue
        if not can:
            failures.append((rel, "NO CANONICAL", "frontmatter needs canonical: <path> | self"))
            continue
        if not fm.get("verified"):
            warnings.append((rel, "NO VERIFIED", "no date of the last check"))

        if kind == "installed":
            if not (VAULT / can).exists():
                failures.append((rel, "DEAD POINTER", "canonical `%s` does not exist" % can))
            elif can != real and real is not None and can != "self":
                # the executable's name differs from the card's name (a legitimate
                # alias): it only requires the declared path to exist, already
                # checked above
                pass
            if POINTER_MARK not in body:
                failures.append((rel, "NO SOURCE BLOCK",
                                 "an installed card needs the block that declares it is not the executable"))
            n = len([x for x in body.splitlines() if x.strip()])
            if n > MAX_POINTER_LINES:
                failures.append((rel, "BLOATED POINTER",
                                 "%d body lines (limit %d): the pointer is turning into a copy"
                                 % (n, MAX_POINTER_LINES)))
            target = VAULT / can
            if target.exists():
                equal = dense_lines(body) & dense_lines(read(target))
                if len(equal) >= MIN_EQUAL_LINES:
                    failures.append((rel, "COPY DETECTED",
                                     "%d lines identical to `%s`: the card is duplicating the executable again"
                                     % (len(equal), can)))
        else:
            if real:
                failures.append((rel, "PROMOTED WITHOUT CONVERTING",
                                 "`%s` exists: the card became a copy, convert it to a pointer" % real))
            if can != "self":
                failures.append((rel, "WRONG CANONICAL", "a library card needs canonical: self"))
            if LIBRARY_MARK not in body:
                failures.append((rel, "NO BANNER",
                                 "a library card needs the banner that declares it the canonical source"))

        if index_text and name not in index_text:
            failures.append((rel, "NOT IN CATALOG",
                             "does not appear in AIOS/index.md: run --catalog"))

    for d in sorted(SKILLS.iterdir()) if SKILLS.exists() else []:
        if not d.is_dir():
            continue
        skill = d / "SKILL.md"
        if not skill.exists():
            failures.append((".claude/skills/%s" % d.name, "NO SKILL.md", "skill folder with no executable"))
            continue
        fm, _ = frontmatter(read(skill))
        if not fm.get("name") or not fm.get("description"):
            failures.append((".claude/skills/%s/SKILL.md" % d.name, "SKILL FRONTMATTER",
                             "missing name or description: Claude Code does not register the skill"))
        if d.name not in cards:
            failures.append((".claude/skills/%s" % d.name, "EXECUTABLE WITHOUT CARD",
                             "installed but invisible to the vault: create AIOS/skills/%s.md" % d.name))

    pointed = {c["fm"].get("canonical", "") for c in cards.values()}
    for c in sorted(CMDS.glob("*.md")) if CMDS.exists() else []:
        rel = ".claude/commands/%s" % c.name
        if c.stem not in cards and rel not in pointed:
            warnings.append((rel, "COMMAND WITHOUT CARD", "command with no note in the vault (listed in the index)"))

    return failures, warnings


# ============================ BLOCK B: internal integrity of the skill =======

def configured_mcps():
    """Reads the MCP servers from the Claude Code config (global + vault scope).

    Reading from the config instead of hard-coding the list is what keeps the
    checker from flagging a ghost server just because someone installed a new MCP.
    """
    names = set(MCP_CONNECTORS)
    cfg = Path(os.path.expanduser("~/.claude.json"))
    if not cfg.exists():
        return names, False
    try:
        d = json.loads(cfg.read_text(encoding="utf-8", errors="replace"))
    except (ValueError, OSError):
        return names, False
    names |= set(d.get("mcpServers") or {})
    for proj, v in (d.get("projects") or {}).items():
        if Path(proj).resolve() == VAULT:
            names |= set((v or {}).get("mcpServers") or {})
    return names, True


def skill_files(d):
    """Every internal file of the skill, relative to its root."""
    out = []
    for p in sorted(d.rglob("*")):
        if p.is_file() and p.suffix.lower() in INTERNAL and p.name != "SKILL.md":
            out.append(p.relative_to(d).as_posix())
    return out


def contract_block(text):
    """The body of `## Contract` up to the next level-2 heading, or None."""
    m = re.search(r"^(#{2,3}) Contract\s*$(.*?)(?=^ |\Z)", text, re.M | re.S)
    return m.group(2) if m else None


def subsection_paths(block, title):
    """Every backticked path inside a `#### <title>` subsection."""
    m = re.search(r"^#+ %s\s*$(.*?)(?=^#+ |\Z)" % re.escape(title),
                  block, re.M | re.S)
    if not m:
        return []
    return [c for c in re.findall(r"`([^`]+)`", m.group(1)) if "/" in c]


def check_contract(rel, text, name):
    """The four contract findings for a writer. Works for a skill and a command."""
    out = []
    block = contract_block(text)
    if block is None:
        return [(rel, "NO CONTRACT",
                 "writes to the vault and does not declare the `Contract` section")]

    missing = [t for t in CONTRACT_SUBSECTIONS
               if not re.search(r"^#+ %s\s*$" % re.escape(t), block, re.M)]
    if missing:
        out.append((rel, "INCOMPLETE CONTRACT", "missing the section %s"
                    % ", ".join("`%s`" % f for f in missing)))

    writes = subsection_paths(block, "Writes")
    top = {d.name for d in VAULT.iterdir() if d.is_dir()}
    for cand in subsection_paths(block, "Reads") + writes:
        seg0 = cand.split("/")[0]
        # `logs/` is a generic relative reference and is not checked. But a
        # destination that LOOKS like a top-level folder and does not exist is the
        # most dangerous case: it is a write declared into an invented place.
        # Found by a negative test, when `99 Ghost/` passed clean through the
        # previous filter.
        if seg0 in top:
            pref = real_prefix(cand)
            if pref and not (VAULT / pref).exists():
                out.append((rel, "CONTRACT POINTS TO NOTHING",
                            "declares `%s` and `%s` does not exist" % (cand, pref)))
        elif RE_VAULT_TOP.match(seg0):
            out.append((rel, "CONTRACT POINTS TO NOTHING",
                        "declares `%s` and the top-level folder `%s` does not exist"
                        % (cand, seg0)))

    routing = read(ROUTING) if ROUTING.exists() else ""
    for cand in writes:
        root = cand.split("/")[0]
        if root and root not in routing:
            out.append((rel, "UNROUTED DESTINATION",
                        "writes to `%s`, absent from knowledge-routing" % root))
    return out


def real_prefix(path):
    """The part of the path before the first segment with a placeholder."""
    parts = []
    for seg in path.split("/"):
        if RE_PLACEHOLDER.search(seg):
            break
        parts.append(seg)
    return "/".join(parts)


def check_internal(installed):
    """Looks INSIDE each skill. See the module docstring, block B."""
    failures, warnings = [], []
    servers, read_cfg = configured_mcps()

    for d in sorted(SKILLS.iterdir()) if SKILLS.exists() else []:
        if not d.is_dir() or not (d / "SKILL.md").exists():
            continue
        name = d.name
        rel_skill = ".claude/skills/%s" % name
        internal = skill_files(d)
        texts = {}
        for p in sorted(d.rglob("*.md")):
            texts[p.relative_to(d).as_posix()] = read(p)
        blob = "\n".join(texts.values())

        # 1. DEAD REFERENCE: the skill tells the agent to read a file that does
        #    not exist. Resolves in 3 places: the skill root, the folder of the
        #    citing file, and the root of .claude/skills/ (a skill can legitimately
        #    point to another skill's reference; that is not a defect).
        def exists(target, base):
            lean = re.sub(r"^~?/?\.claude/skills/", "", target)
            return ((d / target).exists() or (d / base / target).exists()
                    or (SKILLS / target).exists() or (SKILLS / lean).exists())

        for origin, txt in texts.items():
            base = Path(origin).parent
            linked = set()
            for m in RE_MD_LINK.finditer(txt):
                target = m.group(1)
                linked.add(target)
                if target.lower().endswith(INTERNAL) and not exists(target, base):
                    failures.append(("%s/%s" % (rel_skill, origin), "DEAD REFERENCE",
                                     "links `%s`, which does not exist" % target))
            seen = set()
            for m in RE_BARE_PATH.finditer(txt):
                target = m.group(1).rstrip(".,;:)`")
                if target in linked or target in seen:
                    continue
                seen.add(target)
                if target.lower().endswith(INTERNAL) and not exists(target, base):
                    warnings.append(("%s/%s" % (rel_skill, origin), "NONEXISTENT PATH",
                                     "cites `%s`, which does not exist (illustrative?)" % target))

        # 2. ORPHAN REFERENCE: a reference document that no text of the skill
        #    points to. Only .md, on purpose: the defect here is KNOWLEDGE that the
        #    skill carries and nobody reads, which ages in silence until it
        #    contradicts the process. An orphan code module is another matter (and
        #    what cites it is the import, not the prose), so it stays out to avoid
        #    drowning the signal.
        for file in internal:
            if not file.lower().endswith(".md"):
                continue
            if file in blob or Path(file).name in blob:
                continue
            warnings.append(("%s/%s" % (rel_skill, file), "ORPHAN REFERENCE",
                             "document that no file of the skill cites: it ages with nobody watching"))

        # 3. GHOST SIBLING SKILL: tells the agent to use a skill that is not installed.
        for origin, txt in texts.items():
            for line in txt.splitlines():
                if not re.search(r"(?i)\bskills?\b", line):
                    continue
                # a line that DECLARES the absence is already the correction, not the defect
                if RE_NEGATION.search(line) or RE_FOREIGN.search(line):
                    continue
                for tok in RE_SKILLISH.findall(line):
                    if tok in installed or tok == name:
                        continue
                    if (d / tok).exists() or any(tok in a for a in internal):
                        continue
                    warnings.append(("%s/%s" % (rel_skill, origin), "GHOST SIBLING SKILL",
                                     "points to the skill `%s`, which is not installed" % tok))

        # 4. FOREIGN PATH: an adaptation that did not go all the way. Same rule as
        #    the others: a line that WARNS that the path is from elsewhere ("did
        #    not come along") is the correction, not the defect.
        for origin, txt in texts.items():
            for pattern, what in FOREIGN_PATHS:
                for line in txt.splitlines():
                    m = re.search(pattern, line)
                    if not m or RE_NEGATION.search(line) or RE_FOREIGN.search(line):
                        continue
                    warnings.append(("%s/%s" % (rel_skill, origin), "FOREIGN PATH",
                                     "%s: `%s`" % (what, m.group(0))))
                    break

        # 5. GHOST MCP: a tool that does not exist in this install.
        #    Citing a server to FORBID its use is legitimate, so a negated line
        #    does not count. E.g.: "NEVER <service>, the hook blocks mcp__<service>__*".
        if read_cfg:
            used = {}
            for line in blob.splitlines():
                if RE_NEGATION.search(line):
                    continue
                for srv in RE_MCP.findall(line):
                    used.setdefault(srv, line.strip()[:70])
            for srv, ctx in sorted(used.items()):
                if srv not in servers:
                    failures.append((rel_skill, "GHOST MCP",
                                     "uses `mcp__%s__*`, server not configured" % srv))

        # 7. GHOST HOOK: the skill claims that a hook protects something and the
        #    hook does not exist on disk. It comes from a real case: two content
        #    skills said that a blocking hook stopped image generation, and the
        #    file was never there. A guarantee that does not run is worse than no
        #    guarantee, because it switches off the human check.
        for origin, txt in texts.items():
            for line in txt.splitlines():
                if RE_NEGATION.search(line):
                    continue
                for m in RE_HOOK.finditer(line):
                    target = Path(m.group(1))
                    if any((root / target.name).exists() for root in HOOK_DIRS):
                        continue
                    failures.append(("%s/%s" % (rel_skill, origin), "GHOST HOOK",
                                     "claims that `%s` protects something, and the hook does not exist"
                                     % target.name))

        # 6. OUTDATED MODEL
        m = re.search(OUTDATED_MODELS, blob, re.I)
        if m:
            warnings.append((rel_skill, "OUTDATED MODEL",
                             "cites `%s`: replace it with the current model" % m.group(0)))

        # 8. I/O CONTRACT (pattern extracted from benai-skills).
        #    A skill that writes to the vault declares what it reads (with what to
        #    do if it is missing), what it writes, and what it NEVER writes,
        #    routing each denied item to the correct owner. Without that the skill
        #    writes wherever it wants, which is how orphan notes and dead wikilinks
        #    are born. The contract only counts if it is checked: a card that
        #    looks right and guides wrong is worse than no card, and the same
        #    disease applies to a contract.
        if name in WRITERS:
            findings = check_contract(rel_skill, texts.get("SKILL.md", ""), name)
            for f in findings:
                (warnings if f[1] == "UNROUTED DESTINATION"
                 or (f[1] == "NO CONTRACT"
                     and name not in CONTRACT_REQUIRED) else failures).append(f)

    # A writer that lives in .claude/commands/ instead of .claude/skills/. The
    # loop above does not reach it, and leaving it out would give ghost coverage,
    # which is worse than no coverage. So its contract is checked here, with the
    # same ruler, and the gap only becomes a warning when the file is gone.
    seen_skills = {d.name for d in SKILLS.iterdir()
                   if SKILLS.exists() and d.is_dir() and (d / "SKILL.md").exists()}
    for name in WRITERS:
        if name in seen_skills:
            continue
        cmd = CMDS / ("%s.md" % name)
        rel = ".claude/commands/%s.md" % name
        if not cmd.exists():
            warnings.append((rel, "WRITER MISSING",
                             "declared in WRITERS and does not exist either as "
                             "a skill or as a command"))
            continue
        failures.extend(check_contract(rel, read(cmd), name))

    return failures, warnings


def rules_report():
    """Gathers the normative lines of each skill for a human read.

    A regex does not decide semantic contradiction. This is not a check: it
    reduces 60 reference files to a few dozen rule lines, grouped by skill, so
    you find the conflict in seconds instead of rereading everything.
    """
    for d in sorted(SKILLS.iterdir()) if SKILLS.exists() else []:
        if not d.is_dir() or not (d / "SKILL.md").exists():
            continue
        refs = [p for p in sorted(d.rglob("*.md")) if p.name != "SKILL.md"]
        if not refs:
            continue  # with no reference there is nothing to contradict
        blocks = []
        for p in [d / "SKILL.md"] + refs:
            rules = []
            for i, line in enumerate(read(p).splitlines(), 1):
                s = line.strip().lstrip("->*|# ").strip()
                if 25 <= len(s) <= 230 and RE_NORMATIVE.search(s):
                    rules.append((i, s))
            if rules:
                blocks.append((p.relative_to(d).as_posix(), rules))
        if len(blocks) < 2:
            continue  # a rule in a single file contradicts nobody
        print("\n=== %s (%d files with rules) ===" % (d.name, len(blocks)))
        for origin, rules in blocks:
            print("\n  -- %s" % origin)
            for i, s in rules:
                print("     %4d  %s" % (i, s))


def build_catalog(cards):
    inst_skill, inst_cmd, library = [], [], []
    for name, c in sorted(cards.items()):
        row = (name, c["fm"].get("canonical", ""), summary_of(c["body"]))
        if c["fm"].get("kind") == "library":
            library.append(row)
        elif row[1].startswith(".claude/commands/"):
            inst_cmd.append(row)
        else:
            inst_skill.append(row)

    out = [START, ""]
    out.append("#### Installed: %d pointer cards (%d skills, %d commands)"
               % (len(inst_skill) + len(inst_cmd), len(inst_skill), len(inst_cmd)))
    out.append("")
    out.append("The card is not the executable: it exists for the graph and for routing. "
               "Canonical source in the middle column.")
    out.append("")
    for title, group in (("Skills", inst_skill), ("Commands", inst_cmd)):
        if not group:
            continue
        out.append("**%s**" % title)
        out.append("")
        out.append("| Card | Canonical source | What it does |")
        out.append("|---|---|---|")
        for name, can, summary in group:
            out.append("| [[AIOS/skills/%s\\|%s]] | `%s` | %s |" % (name, name, can, summary))
        out.append("")
    out.append("#### Library: %d cards that are the source themselves" % len(library))
    out.append("")
    out.append("No executable installed. The content lives here and cannot diverge from anything. "
               "To promote one, copy it to `.claude/skills/` and replace this note with a pointer.")
    out.append("")
    out.append("| Card | What it does |")
    out.append("|---|---|")
    for name, _can, summary in library:
        out.append("| [[AIOS/skills/%s\\|%s]] | %s |" % (name, name, summary))
    out.append("")
    out.append(END)
    return "\n".join(out)


def write_catalog(cards):
    text = read(INDEX)
    block = build_catalog(cards)
    if START in text and END in text:
        start = text.index(START)
        end = text.index(END) + len(END)
        new = text[:start] + block + text[end:]
    else:
        print("markers not found in AIOS/index.md: add")
        print("  %s\n  %s" % (START, END))
        return 1
    INDEX.write_text(new, encoding="utf-8", newline="\n")
    print("catalog regenerated in AIOS/index.md (%d cards)." % len(cards))
    return 0


def main():
    # A vault with no AIOS/skills does not use cards: block A (the card/executable
    # contract) does not apply and the catalog is kept by hand in AIOS/index.md.
    # Block B (internal integrity of each skill) runs the same.
    no_cards = not CARDS.is_dir()
    cards = {} if no_cards else load_cards()
    if "--catalog" in sys.argv:
        if no_cards:
            print("This vault does not use cards in AIOS/skills: the catalog in AIOS/index.md is kept by hand.")
            return 0
        return write_catalog(cards)
    if "--rules" in sys.argv:
        rules_report()
        return 0

    installed = {d.name for d in SKILLS.iterdir()
                 if SKILLS.exists() and d.is_dir() and (d / "SKILL.md").exists()}
    installed |= {c.stem for c in CMDS.glob("*.md")} if CMDS.exists() else set()

    failures_a, warnings_a = check(cards)
    if no_cards:
        failures_a = [f for f in failures_a if f[1] != "EXECUTABLE WITHOUT CARD"]
        warnings_a = [w for w in warnings_a if w[1] != "COMMAND WITHOUT CARD"]
    failures_b, warnings_b = check_internal(installed)

    inst = sum(1 for c in cards.values() if c["fm"].get("kind") == "installed")
    n_ref = sum(1 for d in SKILLS.iterdir() if d.is_dir()
                for p in d.rglob("*.md") if p.name != "SKILL.md") if SKILLS.exists() else 0
    if no_cards:
        print("BLOCK A  no cards in this vault: only the frontmatter of each SKILL.md is checked")
    else:
        print("BLOCK A  %d cards (%d installed, %d library)"
              % (len(cards), inst, len(cards) - inst))
    print("BLOCK B  %d skills installed, %d reference files"
          % (len(installed), n_ref))

    for title, items in (("A - card/executable contract", warnings_a),
                         ("B - internal integrity", warnings_b)):
        if items:
            print("\n%d warning(s) from block %s (do not fail the check):\n" % (len(items), title))
            for rel, kind, detail in items:
                print("  %s  [%s] %s" % (rel, kind, detail))

    failures = failures_a + failures_b
    if not failures:
        print("\nPASSED: one source of truth per skill, no dead pointer,")
        print("        no dead reference, no ghost tool.")
        return 0
    print("\n%d failure(s):\n" % len(failures))
    for rel, kind, detail in failures:
        print("  %s  [%s] %s" % (rel, kind, detail))
    return 1


if __name__ == "__main__":
    sys.exit(main())
